"""Self-consistent Hubbard U bootstrap at target (T, P) points.

For each requested (T, P) point, generates a remote task that iterates
``pw.x scf(U) -> hp.x -> U_new`` until ``|U_new - U| < tol``, producing the
``u_tp`` table consumed by ``fp_hubbard.u_tp`` (U_init for labeling) and by
the AIMD stage (HUBBARD U in magnetic-phase MD).

The remote driver ``uinit_loop.py`` only needs python3 + numpy (mirrors
``dpgen.generator.lib.mlu_frame``); QE runs are launched through the machine
commands like every other dpgen task.
"""

import glob
import json
import os

from dpgen.generator.lib import qe_hp

FS_TO_AU = 1.0 / 0.0483776866  # femtoseconds -> Hartree atomic units of time


def gen_uinit_tasks(jdata, mdata):
    """Generate one self-consistent U task per (T, P) point.

    jdata["uinit"]: dict with
      points   : list of {"T": K, "P": bar, "structure": path-to-POSCAR}
      tol      : U convergence tolerance in eV (default 0.02)
      max_iter : outer loop cap (default 5)
      plus pw/hp parameters (element, manifold, u0, ecutwfc, ecutrho,
      kspacing, smearing T from each point, nspin, starting_mag, press_kbar).
    Writes ``uinit/T{T}_P{P}/{uinit_loop.py, pw.scf.in.000, pw.hp.in, run.sh}``
    and returns the list of task directories.
    """
    ui = jdata["uinit"]
    element = ui.get("element", jdata["type_map"][0])
    manifold = ui.get("manifold", "3d")
    u0 = float(ui.get("u0", 1.0))
    tol = float(ui.get("tol", 0.02))
    max_iter = int(ui.get("max_iter", 5))
    kspacing = ui.get("kspacing", 0.6)
    pseudo_files = dict(zip(jdata["type_map"], jdata.get("fp_pp_files", [])))
    mass_map = dict(zip(jdata["type_map"], jdata["mass_map"]))
    pw_cmd = mdata.get("fp_pw_command", "pw.x")
    hp_cmd = mdata.get("fp_hp_command", "hp.x")

    import dpdata

    root = "uinit"
    os.makedirs(root, exist_ok=True)
    # ship the remote helpers once
    import shutil

    shutil.copyfile(
        os.path.join(os.path.dirname(qe_hp.__file__), "mlu_frame.py"),
        os.path.join(root, "mlu_frame.py"),
    )
    shutil.copyfile(
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "uinit_loop.py"),
        os.path.join(root, "uinit_loop.py"),
    )

    tasks = []
    for pt in ui["points"]:
        temp = float(pt["T"])
        press = float(pt.get("P", 0.0))
        sys_data = dpdata.System(pt["structure"], fmt="vasp/poscar").data
        task_name = "T%04dK_P%08.2fbar" % (temp, press)
        task_dir = os.path.join(root, task_name)
        os.makedirs(task_dir, exist_ok=True)

        cell = sys_data["cells"][0].reshape([3, 3])
        coords_crystal = qe_hp.cartesian_to_crystal(sys_data["coords"][0], cell)
        atom_types = sys_data["atom_types"]
        kmesh = qe_hp.compute_kmesh(cell, kspacing)
        degauss = qe_hp.temperature_to_degauss(temp)

        scf_text = qe_hp.generate_scf_input(
            cell,
            coords_crystal,
            atom_types,
            jdata["type_map"],
            pseudo_dir="./",
            pseudo_files=pseudo_files,
            degauss=degauss,
            ecutwfc=ui.get("ecutwfc", 80),
            ecutrho=ui.get("ecutrho", 400),
            kpoints=kmesh,
            mass_map=mass_map,
            prefix="pw",
            u_init=u0,
            nspin=ui.get("nspin", 2),
            starting_magnetization={element: float(ui.get("starting_mag", 2.2))},
            conv_thr=ui.get("conv_thr", 1e-5),
            u_element=element,
            u_manifold=manifold,
        )
        with open(os.path.join(task_dir, "pw.scf.in.000"), "w") as fp:
            fp.write(scf_text)
        hp_text = qe_hp.generate_hp_input(
            prefix="pw",
            nq1=ui.get("nq1", 1),
            nq2=ui.get("nq2", 1),
            nq3=ui.get("nq3", 1),
        )
        with open(os.path.join(task_dir, "pw.hp.in"), "w") as fp:
            fp.write(hp_text)

        # QE press is in kbar; P in the table is bar. The NPT cell control
        # (&CONTROL cell_dynamics/press/cell_dofree) is injected by
        # uinit_loop.py when regenerating each iteration's input.

        loop_conf = {
            "element": element,
            "manifold": manifold,
            "tol": tol,
            "max_iter": max_iter,
            "u0": u0,
            "T": temp,
            "P_bar": press,
            "press_kbar": press / 1e3,
            "npt": bool(ui.get("npt", True) and pt.get("P", 0.0) > 0),
        }
        with open(os.path.join(task_dir, "uinit.json"), "w") as fp:
            json.dump(loop_conf, fp, indent=2)

        with open(os.path.join(task_dir, "run.sh"), "w") as fp:
            fp.write(
                "#!/bin/bash\n"
                "# self-consistent U loop generated by dpgen mlu uinit\n"
                "set -u\n"
                "exec >> output 2>&1\n"
                f"python3 ../uinit_loop.py . '{pw_cmd}' '{hp_cmd}'\n"
                "if [ ! -f u_result.json ]; then\n"
                '  echo "UINIT_FAIL"; touch UINIT_FAILED; exit 1\n'
                "fi\n"
                'echo "UINIT_OK"\n'
            )
        os.chmod(os.path.join(task_dir, "run.sh"), 0o755)
        tasks.append(task_dir)
    return tasks


def collect_uinit_results(jdata):
    """Gather u_result.json files into the u_tp table (list + u_tp.json).

    Returns the list of {'T','P','U','n_iter','converged'} entries; writes
    ``uinit/u_tp.json`` for direct use as ``fp_hubbard.u_tp``.
    """
    table = []
    for res in sorted(glob.glob(os.path.join("uinit", "*", "u_result.json"))):
        with open(res) as fp:
            r = json.load(fp)
        table.append(
            {
                "T": r["T"],
                "P": r.get("P_bar", r.get("P", 0.0)),
                "U": r["U"],
                "n_iter": r.get("n_iter"),
                "converged": r.get("converged", False),
            }
        )
    if table:
        with open(os.path.join("uinit", "u_tp.json"), "w") as fp:
            json.dump(table, fp, indent=2)
    return table
